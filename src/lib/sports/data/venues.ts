type VenueInput = Omit<Venue, "guide" | "travel" | "hotels" | "image"> &
  Partial<Pick<Venue, "guide" | "travel" | "hotels" | "image">>;

function venue(input: VenueInput): Venue {
  return {
    image: img.bowlDay,
    guide: standardGuide,
    travel: genericTravel(input.city, input.name),
    hotels: [],
    ...input,
  };
}

function genericTravel(city: string, name: string): TravelTip[] {
  return [
    { mode: "air", title: "By air", text: `Fly into ${city}'s main international airport and allow around an hour to reach ${name} on matchday.` },
    { mode: "train", title: "By public transport", text: `Local rail, metro and tram services run extra trains on matchdays. Expect busy platforms after the final whistle.` },
    { mode: "car", title: "By car", text: "Matchday road closures apply around the stadium. Parking is limited and not included in packages." },
  ];
}

