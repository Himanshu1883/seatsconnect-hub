const curated: Record<string, Package[]> = {
  "etihad-stadium": etihad,
  "old-trafford": oldTrafford,
  "tottenham-hotspur-stadium": tottenham,
};

export function packagesForVenue(venue: Venue): Package[] {
  if (curated[venue.slug]) return curated[venue.slug];
  if (venue.mapLayout && venue.mapLayout !== "pitch") return genericEvent(venue);
  if (venue.image.includes("/experiences/venues/")) return genericEvent(venue);
  return generic(venue);
}

