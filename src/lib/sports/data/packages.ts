function venueViewMedia(venue: Venue, standLabel: string): Media[] {
  const overview = venueMapImage(venue.slug);
  return [
    m(venue.image, `${venue.name} — ${standLabel}`, "view"),
    m(overview, `${venue.name} — venue overview`, "stadium"),
  ];
}

function packageViewMedia(venue: Venue, standLabel: string): Media[] {
  if (venue.mapLayout && venue.mapLayout !== "pitch") return venueViewMedia(venue, standLabel);
  if (venue.image.includes("/experiences/venues/")) return venueViewMedia(venue, standLabel);
  return viewMedia(standLabel);
}

type Draft = Omit<Package, "details" | "itinerary"> & {
  dining?: string;
  drinks?: string;
  programme?: string;
  dress?: string;
  delivery?: string;
  entry?: string;
  itinerary?: ItineraryStep[];
};

type EventDraft = Draft & { event?: boolean };

function pkg(draft: EventDraft): Package {
  const { dining, drinks, programme, dress, delivery, entry, itinerary, event, ...rest } = draft;
  const defaultItinerary = event
    ? rest.tier === "ticket"
      ? eventTicketDay
      : eventLoungeDay
    : rest.tier === "ticket"
      ? ticketDay
      : loungeDay;
  return {
    ...rest,
    itinerary: itinerary ?? defaultItinerary,
    details: [
      { label: "Entry & access", value: entry ?? (event ? "Official event ticket included" : "Match ticket included") },
      { label: "Seating", value: rest.seating[0] ?? rest.location },
      { label: "Dining", value: dining ?? "Not included" },
      { label: "Drinks", value: drinks ?? "Cash bar available" },
      { label: "Programme", value: programme ?? "Not specified for this package" },
      {
        label: "Dress code",
        value: dress ?? (event ? "Smart casual unless stated by the organiser." : "Smart casual. Away colours are not permitted."),
      },
      {
        label: "Audience",
        value: event ? "Families and children welcome unless age restrictions apply." : `Families and children welcome. ${homeOnly}`,
      },
      {
        label: "Ticket delivery",
        value: delivery ?? (event ? "Mobile tickets from the official organiser, 2–5 days before the event" : "Mobile tickets via the official club app, 2–4 days before the match"),
      },
    ],
  };
}

